-- 10. Existing checkout RPC: keep canonical architecture
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.place_website_order_atomic(
  p_customer_id text,
  p_customer_name text,
  p_customer_phone text,
  p_shipping_address text,
  p_landmark text DEFAULT NULL,
  p_pincode text DEFAULT NULL,
  p_payment_method text DEFAULT 'cod',
  p_idempotency_key text DEFAULT NULL,
  p_items jsonb DEFAULT '[]'::jsonb
)
RETURNS TABLE (
  id text,
  total numeric,
  subtotal numeric,
  status text,
  payment_status text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_auth_user uuid;
  v_customer_uuid uuid;
  v_order_id text;
  v_item jsonb;
  v_product_id bigint;
  v_quantity integer;
  v_product record;
  v_unit_price numeric;
  v_line_total numeric;
  v_subtotal numeric := 0;
BEGIN
  v_auth_user := auth.uid();
  IF v_auth_user IS NULL THEN
    RAISE EXCEPTION 'Authentication required for website checkout';
  END IF;

  IF p_customer_id IS NULL OR btrim(p_customer_id) = '' THEN
    RAISE EXCEPTION 'customer_id is required';
  END IF;

  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' THEN
    RAISE EXCEPTION 'items must be a JSON array';
  END IF;

  IF jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Cart is empty';
  END IF;

  v_customer_uuid := p_customer_id::uuid;
  IF v_auth_user <> v_customer_uuid THEN
    RAISE EXCEPTION 'Customer identity mismatch';
  END IF;

  IF p_idempotency_key IS NOT NULL THEN
    SELECT o.id INTO v_order_id
    FROM public.orders o
    WHERE o.customer_id = p_customer_id
      AND o.idempotency_key = p_idempotency_key
    LIMIT 1;

    IF v_order_id IS NOT NULL THEN
      RETURN QUERY
      SELECT o.id::text,
             COALESCE(o.total, 0),
             COALESCE(o.subtotal, 0),
             COALESCE(o.status, 'pending'),
             COALESCE(o.payment_status, 'pending')
      FROM public.orders o
      WHERE o.id = v_order_id;
      RETURN;
    END IF;
  END IF;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    v_product_id := NULLIF((v_item ->> 'product_id')::text, '')::bigint;
    v_quantity := NULLIF((v_item ->> 'quantity')::text, '')::integer;

    IF v_product_id IS NULL OR v_quantity IS NULL OR v_quantity <= 0 THEN
      RAISE EXCEPTION 'Invalid item payload';
    END IF;

    SELECT p.* INTO v_product
    FROM public.products p
    WHERE p.id = v_product_id
    FOR UPDATE;

    IF v_product.id IS NULL THEN
      RAISE EXCEPTION 'Product not found: %', v_product_id;
    END IF;

    IF v_product.is_deleted = TRUE THEN
      RAISE EXCEPTION 'Product is unavailable: %', v_product_id;
    END IF;

    IF v_product.is_active = FALSE THEN
      RAISE EXCEPTION 'Product is inactive: %', v_product_id;
    END IF;

    IF COALESCE(v_product.stock, 0)::numeric < v_quantity THEN
      RAISE EXCEPTION 'Insufficient stock for product %', v_product_id;
    END IF;

    v_unit_price := COALESCE(
      v_product.sale_rate,
      v_product.onlinerate,
      v_product.online_rate,
      v_product.retail_rate,
      v_product.restrate,
      v_product.selling_price,
      0
    )::numeric;

    IF v_unit_price <= 0 THEN
      RAISE EXCEPTION 'Product price missing for product %', v_product_id;
    END IF;

    v_line_total := v_unit_price * v_quantity;
    v_subtotal := v_subtotal + v_line_total;
  END LOOP;

  INSERT INTO public.orders (
    id,
    customer_id,
    customer_name,
    customer_phone,
    shipping_address,
    delivery_address,
    landmark,
    pincode,
    subtotal,
    total,
    total_amount,
    payment_method,
    payment_mode,
    payment_status,
    order_status,
    status,
    items,
    idempotency_key,
    created_at,
    updated_at
  )
  VALUES (
    gen_random_uuid()::text,
    p_customer_id,
    p_customer_name,
    p_customer_phone,
    p_shipping_address,
    p_shipping_address,
    p_landmark,
    p_pincode,
    v_subtotal,
    v_subtotal,
    v_subtotal,
    p_payment_method,
    p_payment_method,
    'pending',
    'pending',
    'pending',
    p_items,
    p_idempotency_key,
    NOW(),
    NOW()
  )
  RETURNING id INTO v_order_id;

  RETURN QUERY
  SELECT v_order_id,
         v_subtotal,
         v_subtotal,
         'pending',
         'pending';
END;
$$;

