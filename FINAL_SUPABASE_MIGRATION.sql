-- -----------------------------------------------------------------------------
-- 11. Wallet RPC: secure adjustment function
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.adjust_wallet_balance(
  p_user_id uuid,
  p_delta numeric,
  p_reason text,
  p_reference_type text DEFAULT NULL,
  p_reference_id text DEFAULT NULL
)
RETURNS TABLE (
  wallet_id bigint,
  new_balance numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_wallet_id bigint;
  v_current_balance numeric;
  v_new_balance numeric;
BEGIN
  IF p_user_id IS NULL THEN
    RAISE EXCEPTION 'user_id is required';
  END IF;

  INSERT INTO public.wallets (user_id, balance, currency, status)
  VALUES (p_user_id, 0, 'INR', 'active')
  ON CONFLICT (user_id)
  DO NOTHING;

  SELECT id, balance
    INTO v_wallet_id, v_current_balance
  FROM public.wallets
  WHERE user_id = p_user_id
  FOR UPDATE;

  v_new_balance := COALESCE(v_current_balance, 0) + COALESCE(p_delta, 0);

  UPDATE public.wallets
  SET balance = v_new_balance,
      updated_at = NOW()
  WHERE id = v_wallet_id;

  INSERT INTO public.wallet_transactions (
    wallet_id,
    user_id,
    entry_type,
    amount,
    currency,
    reference_type,
    reference_id,
    reason
  )
  VALUES (
    v_wallet_id,
    p_user_id,
    CASE WHEN COALESCE(p_delta, 0) >= 0 THEN 'credit' ELSE 'debit' END,
    ABS(COALESCE(p_delta, 0)),
    'INR',
    p_reference_type,
    p_reference_id,
    p_reason
  );

  RETURN QUERY
  SELECT v_wallet_id, v_new_balance;
END;
$$;

REVOKE ALL ON FUNCTION public.adjust_wallet_balance(uuid, numeric, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.adjust_wallet_balance(uuid, numeric, text, text, text) TO authenticated;

